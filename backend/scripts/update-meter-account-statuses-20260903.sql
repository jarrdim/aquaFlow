CREATE TEMP TABLE matched_updates ON COMMIT DROP AS
SELECT
  updates.meter_number,
  updates.account_number,
  updates.source_status,
  meter.meter_id,
  meter.status AS previous_meter_status,
  account.account_id,
  account.account_status AS previous_account_status,
  assignment.assignment_id
FROM status_updates AS updates
LEFT JOIN aquaflow.meters AS meter
  ON meter.meter_number = updates.meter_number
LEFT JOIN aquaflow.customer_accounts AS account
  ON account.account_number = updates.account_number
LEFT JOIN LATERAL (
  SELECT meter_assignment.assignment_id
  FROM aquaflow.meter_assignments AS meter_assignment
  WHERE meter_assignment.meter_id = meter.meter_id
    AND meter_assignment.account_id = account.account_id
  ORDER BY meter_assignment.assignment_date DESC, meter_assignment.assignment_id DESC
  LIMIT 1
) AS assignment ON TRUE;

DO $validation$
DECLARE
  supplied_count INTEGER;
  invalid_count INTEGER;
  examples TEXT;
BEGIN
  SELECT COUNT(*) INTO supplied_count FROM status_updates;
  IF supplied_count <> 1040 THEN
    RAISE EXCEPTION 'Expected 1040 supplied rows, found %', supplied_count;
  END IF;

  SELECT COUNT(*) INTO invalid_count
  FROM matched_updates
  WHERE meter_id IS NULL OR account_id IS NULL;

  SELECT string_agg(meter_number || '/' || account_number, ', ')
  INTO examples
  FROM (
    SELECT meter_number, account_number
    FROM matched_updates
    WHERE meter_id IS NULL OR account_id IS NULL
    ORDER BY account_number
    LIMIT 20
  ) AS invalid;

  IF invalid_count > 0 THEN
    RAISE EXCEPTION
      'Update cancelled: % supplied pair(s) are missing a meter or account. First examples: %',
      invalid_count, examples;
  END IF;
END
$validation$;

UPDATE aquaflow.customer_accounts AS account
SET
  account_status = CASE matched.source_status
    WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
    WHEN 'VACATED' THEN 'CLOSED'
  END,
  updated_at = CURRENT_TIMESTAMP
FROM matched_updates AS matched
WHERE account.account_id = matched.account_id
  AND account.account_status IS DISTINCT FROM CASE matched.source_status
    WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
    WHEN 'VACATED' THEN 'CLOSED'
  END;

UPDATE aquaflow.meters AS meter
SET
  status = CASE matched.source_status
    WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
    WHEN 'VACATED' THEN 'INACTIVE'
  END,
  updated_at = CURRENT_TIMESTAMP
FROM matched_updates AS matched
WHERE meter.meter_id = matched.meter_id
  AND meter.status IS DISTINCT FROM CASE matched.source_status
    WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
    WHEN 'VACATED' THEN 'INACTIVE'
  END;

INSERT INTO aquaflow.meter_events (
  meter_id,
  assignment_id,
  event_type,
  previous_status,
  new_status,
  reason,
  remarks,
  event_date
)
SELECT
  matched.meter_id,
  matched.assignment_id,
  'STATUS_CHANGED',
  matched.previous_meter_status,
  CASE matched.source_status
    WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
    WHEN 'VACATED' THEN 'INACTIVE'
  END,
  'Legacy account status synchronization',
  'Source account status: ' || matched.source_status ||
    '; account number: ' || matched.account_number,
  CURRENT_TIMESTAMP
FROM matched_updates AS matched
WHERE matched.previous_meter_status IS DISTINCT FROM CASE matched.source_status
  WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
  WHEN 'VACATED' THEN 'INACTIVE'
END;

SELECT
  source_status,
  COUNT(*) AS supplied_pairs,
  COUNT(*) FILTER (
    WHERE previous_account_status IS DISTINCT FROM CASE source_status
      WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
      WHEN 'VACATED' THEN 'CLOSED'
    END
  ) AS accounts_changed,
  COUNT(*) FILTER (
    WHERE previous_meter_status IS DISTINCT FROM CASE source_status
      WHEN 'DISCONNECTED' THEN 'DISCONNECTED'
      WHEN 'VACATED' THEN 'INACTIVE'
    END
  ) AS meters_changed
FROM matched_updates
GROUP BY source_status
ORDER BY source_status;

